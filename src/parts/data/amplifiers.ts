/**
 * Op-amps and comparators — verified datasheet data.
 *
 * Rail-relative specs (`relativeTo`) use physical boundary semantics, V = V(rail) + value:
 *  - a high-side limit (output high, CM-range top) has its guaranteed worst case in `min`;
 *  - a low-side limit (output low, CM-range bottom) has its guaranteed worst case in `max`.
 * Converting an absolute datasheet voltage at a stated supply to a rail offset is exact (not
 * estimated); each such spec's note says what was printed.
 * Open-loop gains printed in V/mV are stored in dB (20·log10(V/V)), original in the note.
 */
