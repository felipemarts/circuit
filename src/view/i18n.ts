export const isPT = typeof document !== 'undefined' && document.documentElement.lang.toLowerCase().startsWith('pt');

export function t(key: string): string {
  if (/^exit[0-3]$/.test(key)) return isPT ? PT[`${key}_pt`] ?? key : PT[key] ?? key;
  if (!isPT) return key;
  return PT[key] ?? key;
}
